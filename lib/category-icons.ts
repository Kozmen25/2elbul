// Icons an admin can assign to a category (stored by name in categories.icon).
export const CATEGORY_ICON_MAP: Record<string, LucideIcon> = {
  Smartphone,
  Laptop,
  Tablet,
  Monitor,
  Cpu,
  Gamepad2,
  Joystick,
  Tv,
  Headphones,
  Speaker,
  Car,
  Bike,
  Truck,
  BatteryCharging,
  Home,
  Map: MapIcon,
  Building2,
  CalendarDays,
  Store,
  Wrench,
  Sofa,
  Coffee,
  Frame,
  Refrigerator,
  PackageSearch,
  Cable,
  Shield,
};

export function resolveCategoryIcon(icon: string | null): LucideIcon {
  return (icon && CATEGORY_ICON_MAP[icon]) || PackageSearch;
}
