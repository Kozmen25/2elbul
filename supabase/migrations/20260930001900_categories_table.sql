-- 2026-09-20 — Real, relational category model (single source of truth).
--
-- Until now categories only existed as free text on products.category plus
-- several independent, hand-maintained lists in application code (taxonomy
-- tree, category routes, header menu map, category labels...). This table
-- becomes the one canonical place for the navigable category structure —
-- homepage tiles, header mega-menu and /category/[slug] pages all read from
-- it. Search-query expansion (lib/category-taxonomy.ts) is a separate,
-- unrelated concern and is left untouched.

create table if not exists public.categories (
  id                bigint generated by default as identity primary key,
  slug              text not null unique,
  parent_id         bigint references public.categories(id) on delete cascade,
  name              text not null,
  icon              text,
  short_description text,
  long_description  text,
  match_keywords    text[] not null default '{}',
  exclude_keywords  text[] not null default '{}',
  expected_product_type text,
  display_order     int not null default 0,
  is_active         boolean not null default true,
  created_at        timestamptz not null default now()
);

create index if not exists categories_parent_id_idx
  on public.categories(parent_id);

create index if not exists categories_display_order_idx
  on public.categories(display_order);

alter table public.categories enable row level security;

drop policy if exists "Categories are publicly readable" on public.categories;
create policy "Categories are publicly readable"
  on public.categories
  for select
  to anon, authenticated
  using (is_active);

