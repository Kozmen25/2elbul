create or replace function public.slugify_product_name(value text)
returns text
language sql
immutable
as $$
  select trim(
    both '-' from regexp_replace(
      lower(
        translate(
          coalesce(value, ''),
          'çğıİöşüÇĞIÖŞÜ',
          'cgiiosuCGIOSU'
        )
      ),
      '[^a-z0-9]+',
      '-',
      'g'
    )
  );
$$;

