// Regenerates lib/database.types.ts from the live schema.
// Run after every migration: npm run db:types

import { writeFileSync } from "node:fs";
import path from "node:path";
import { generateTypeScriptTypes, readManagementApiConfig } from "./management-api";

const OUTPUT_FILE = path.join(process.cwd(), "lib", "database.types.ts");
const SCHEMAS = ["public"];
const HEADER = "// Generated by `npm run db:types` from the live Supabase schema. Do not edit by hand.\n\n";

async function main() {
  const types = await generateTypeScriptTypes(readManagementApiConfig(), SCHEMAS);
  writeFileSync(OUTPUT_FILE, HEADER + types);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_FILE)}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
